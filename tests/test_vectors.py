"""
Tests of the test-vector generator against the committed corpus.
"""
import csv
import gzip
import hashlib
import io
import pathlib
import sys

import pytest

from wellclear import vectors

ROOT = pathlib.Path(__file__).resolve().parent.parent

@pytest.fixture(name='corpus', scope='module')
def fixture_corpus():
    with gzip.open(ROOT / 'data' / 'vectors.csv.gz', 'rt', encoding='utf-8', newline='') as file:
        return list(csv.DictReader(file))

def test_corpus_composition(corpus):
    assert len(corpus) == 58983
    assert vectors.categories(corpus) == {
        'cpa': 36000, 'uniform': 12000, 'cliff_hmd': 3000, 'cliff_level': 1200,
        'cliff_static': 600, 'edge': 120, 'sym': 3000, 'shift': 3000, 'robust': 63
    }
    assert tuple(corpus[0]) == vectors.COLUMNS
    assert len({row['id'] for row in corpus}) == len(corpus)

def test_platform_independent_categories_match_corpus(corpus):
    # Edge cases and invalid inputs do not depend on the platform's mathematical library.
    by_id = {row['id']: row for row in corpus}
    for row in vectors.edges() + vectors.robust():
        assert by_id[row['id']] == row

def test_metamorphic_variants_are_exact(corpus):
    by_id = {row['id']: row for row in corpus}
    pairs = (('so', 'si'), ('vo', 'vi'), ('si', 'so'), ('vi', 'vo'))
    for row in corpus:
        if row['cat'] == 'sym':
            base = by_id[row['base']]
            for (a, b) in pairs:
                for axis in 'xyz':
                    assert row[a + axis] == base[b + axis]
            assert all(row[k] == base[k] for k in ('B', 'T', 'DTHR', 'ZTHR', 'TTHR', 'TCOA'))
        elif row['cat'] == 'shift':
            base = by_id[row['base']]
            assert base['cat'] == 'cpa'
            assert all(row[k] == base[k] for k in ('B', 'T', 'DTHR', 'ZTHR', 'TTHR', 'TCOA'))

def test_thresholds_match_daidalus_tables():
    # Values printed by the harness command "tables" for the upstream WCVTable constants.
    assert vectors.TABLES['P1'][:2] == (1222.3200000000002, 137.16)
    assert vectors.TABLES['P2'][0] == 457.20000000000005
    assert vectors.TABLES['NC'][0] == 670.5600000000001
    assert vectors.TABLES['BUFP'][1] == 228.60000000000002

def test_written_corpus_round_trips(tmp_path):
    rows = vectors.edges()
    vectors.write(tmp_path / 'edges.csv', rows)
    assert list(vectors.read(tmp_path / 'edges.csv').values()) == rows
    assert b'\r' not in (tmp_path / 'edges.csv').read_bytes()

@pytest.mark.skipif(
    sys.platform != 'linux' or sys.version_info[:2] != (3, 13),
    reason='the canonical corpus was generated by CPython 3.13 with glibc'
)
def test_regeneration_reproduces_corpus():
    buffer = io.StringIO(newline='')
    writer = csv.DictWriter(buffer, fieldnames=vectors.COLUMNS, lineterminator='\n')
    writer.writeheader()
    writer.writerows(vectors.rows())
    digest = hashlib.sha256(buffer.getvalue().encode('utf-8')).hexdigest()
    sums = (ROOT / 'results' / 'SHA256SUMS').read_text('utf-8').split()
    assert digest == sums[sums.index('vectors.csv') - 1]
